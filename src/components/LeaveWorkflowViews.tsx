// LEAVE LIST, SEARCH/FILTER, HISTORY & INSPECTOR/ADMIN APPROVAL WORKFLOW (#16-#21)
// ============================================================================
interface LeaveListAndInspectionViewProps {
  user: User;
  canReviewAllLeaves: boolean;
  leaves: LeaveRequest[];
  leaveTypes: LeaveType[];
  inspectors: InspectorRecord[];
  settings: SystemSettings;
  mode: 'my_leaves' | 'history' | 'review';
  onEditLeave: (leave: LeaveRequest) => void;
  onCancelLeave: (leaveId: string) => Promise<void>;
  onWorkflowAction: (
    leaveId: string,
    payload: {
      actionType: 'ตรวจสอบ' | 'อนุมัติ' | 'ไม่อนุมัติ' | 'ส่งกลับแก้ไข';
      comment: string;
      actorName: string;
      actorPosition: string;
      signatureDataUrl: string;
    }
  ) => Promise<LeaveRequest>;
  onUploadPdfToDrive: (
    leaveId: string,
    pdfBase64: string,
    fileName: string
  ) => Promise<LeaveRequest | void>;
}

export const LeaveListAndInspectionView: React.FC<LeaveListAndInspectionViewProps> = ({
  user,
  canReviewAllLeaves,
  leaves,
  leaveTypes,
  inspectors,
  settings,
  mode,
  onEditLeave,
  onCancelLeave,
  onWorkflowAction,
  onUploadPdfToDrive,
}) => {
  const [searchQuery, setSearchQuery] = useState('');
  const [statusFilter, setStatusFilter] = useState<string>('ALL');
  const [typeFilter, setTypeFilter] = useState<string>('ALL');
  const [monthFilter, setMonthFilter] = useState<string>('ALL');
  const [yearFilter, setYearFilter] = useState<string>('ALL');

  const [previewLeave, setPreviewLeave] = useState<LeaveRequest | null>(null);
  const [workflowTarget, setWorkflowTarget] = useState<{
    leave: LeaveRequest;
    actionType: 'ตรวจสอบ' | 'อนุมัติ' | 'ไม่อนุมัติ' | 'ส่งกลับแก้ไข';
  } | null>(null);

  const defaultInspector =
    inspectors.find((i) => i.isDefault && i.isActive) || inspectors[0];

  const [actorName, setActorName] = useState('');
  const [actorPosition, setActorPosition] = useState('');
  const [workflowComment, setWorkflowComment] = useState('');
  const [signatureDataUrl, setSignatureDataUrl] = useState('');
  const [isProcessingWorkflow, setIsProcessingWorkflow] = useState(false);
  const [workflowError, setWorkflowError] = useState('');
  const [uploadingLeaveId, setUploadingLeaveId] = useState<string | null>(null);

  const handleQuickGenerateAndUploadDrive = async (leave: LeaveRequest) => {
    setUploadingLeaveId(leave.leaveId);
    try {
      const { pdfBase64, fileName } = await generateOfficialLeavePdf(leave, settings);
      await onUploadPdfToDrive(leave.leaveId, pdfBase64, fileName);
    } catch {
      // handled in parent or document modal
    } finally {
      setUploadingLeaveId(null);
    }
  };

  const openWorkflowModal = (
    leave: LeaveRequest,
    actionType: 'ตรวจสอบ' | 'อนุมัติ' | 'ไม่อนุมัติ' | 'ส่งกลับแก้ไข'
  ) => {
    setWorkflowError('');
    if (actionType === 'ตรวจสอบ') {
      setActorName(defaultInspector?.fullName || settings.defaultInspectorName || user.fullName);
      setActorPosition(
        defaultInspector?.position ||
          settings.defaultInspectorPosition ||
          'หัวหน้าเจ้าหน้าที่กลุ่มงานบุคคล'
      );
      setWorkflowComment('ตรวจสอบสถิติการลาแล้ว เห็นควรอนุญาต');
      setSignatureDataUrl(defaultInspector?.signatureDataUrl || '');
    } else if (actionType === 'อนุมัติ') {
      setActorName(settings.directorName || user.fullName);
      setActorPosition(settings.directorPosition || 'ผู้อำนวยการสถานศึกษา');
      setWorkflowComment('อนุญาต');
      setSignatureDataUrl(settings.directorSignatureUrl || '');
    } else {
      setActorName(user.fullName);
      setActorPosition(user.position || settings.defaultInspectorPosition);
      setWorkflowComment('');
      setSignatureDataUrl('');
    }
    setWorkflowTarget({ leave, actionType });
  };

  const handleConfirmWorkflow = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!workflowTarget) return;
    const { leave, actionType } = workflowTarget;

    if (
      (actionType === 'ไม่อนุมัติ' || actionType === 'ส่งกลับแก้ไข') &&
      !workflowComment.trim()
    ) {
      setWorkflowError(
        actionType === 'ไม่อนุมัติ'
          ? 'กรุณากรอกเหตุผลที่ไม่อนุมัติใบลา'
          : 'กรุณากรอกข้อความแจ้งผู้ยื่นเพื่อแก้ไขใบลา'
      );
      return;
    }

    setIsProcessingWorkflow(true);
    setWorkflowError('');
    try {
      const updatedLeave = await onWorkflowAction(leave.leaveId, {
        actionType,
        comment: workflowComment,
        actorName,
        actorPosition,
        signatureDataUrl,
      });

      // Regenerate official PDF with inspector/approver signature and re-upload to Google Drive (#15, #16, #18)
      if (actionType === 'ตรวจสอบ' || actionType === 'อนุมัติ' || actionType === 'ไม่อนุมัติ') {
        try {
          const { pdfBase64, fileName } = await generateOfficialLeavePdf(updatedLeave, settings);
          await onUploadPdfToDrive(updatedLeave.leaveId, pdfBase64, fileName);
        } catch {
          // non-fatal
        }
      }

      setWorkflowTarget(null);
    } catch (err: any) {
      setWorkflowError(err.message || 'ไม่สามารถบันทึกผลการพิจารณาได้');
    } finally {
      setIsProcessingWorkflow(false);
    }
  };

  const filteredLeaves = useMemo(() => {
    return leaves.filter((l) => {
      if (mode === 'my_leaves' && l.userId !== user.userId) return false;
      if (mode === 'history' && !canReviewAllLeaves && l.userId !== user.userId) return false;

      if (statusFilter !== 'ALL' && l.status !== statusFilter) return false;
      if (typeFilter !== 'ALL' && l.leaveTypeName !== typeFilter) return false;

      const dateParts = parseISODateParts(l.startDate);
      if (monthFilter !== 'ALL' && dateParts && String(dateParts.monthIndex) !== monthFilter) {
        return false;
      }
      if (yearFilter !== 'ALL' && dateParts && String(dateParts.yearBE) !== yearFilter) {
        return false;
      }

      if (searchQuery.trim()) {
        const q = searchQuery.toLowerCase();
        const match =
          l.leaveNumber.toLowerCase().includes(q) ||
          l.fullName.toLowerCase().includes(q) ||
          l.position.toLowerCase().includes(q) ||
          l.leaveTypeName.toLowerCase().includes(q) ||
          l.reason.toLowerCase().includes(q);
        if (!match) return false;
      }
      return true;
    });
  }, [leaves, mode, user.userId, canReviewAllLeaves, statusFilter, typeFilter, monthFilter, yearFilter, searchQuery]);

  const getStatusBadgeStyle = (status: string) => {
    switch (status) {
      case 'อนุมัติแล้ว':
        return 'bg-emerald-50 text-emerald-800 border-emerald-200';
      case 'รอตรวจสอบ':
      case 'ส่งใบลาแล้ว':
        return 'bg-amber-50 text-amber-800 border-amber-200';
      case 'รออนุมัติ':
        return 'bg-blue-50 text-blue-800 border-blue-200';
      case 'ส่งกลับแก้ไข':
        return 'bg-orange-50 text-orange-800 border-orange-200';
      case 'ไม่อนุมัติ':
        return 'bg-rose-50 text-rose-800 border-rose-200';
      default:
        return 'bg-slate-100 text-slate-600 border-slate-200';
    }
  };

  if (previewLeave) {
    return (
      <OfficialLeaveDocument
        leave={previewLeave}
        settings={settings}
        onClose={() => setPreviewLeave(null)}
        onUploadToDrive={onUploadPdfToDrive}
      />
    );
  }

  return (
    <div className="space-y-4">
      {/* Header & Search/Filter Panel (#21) */}
      <div className="bg-white rounded-2xl p-4 border border-slate-200 shadow-xs space-y-3">
        <div className="flex items-center justify-between flex-wrap gap-2">
          <div>
            <h2 className="text-lg font-bold text-slate-900">
              {mode === 'review'
                ? 'ตรวจสอบและอนุมัติใบลาราชการ'
                : mode === 'history'
                ? 'ประวัติการลาและค้นหาเอกสาร'
                : 'รายการใบลาของฉัน'}
            </h2>
            <p className="text-xs text-slate-500">
              พบรายการใบลาทั้งหมด {filteredLeaves.length} รายการ
            </p>
          </div>
        </div>

        <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-5 gap-2.5">
          <div className="relative sm:col-span-2 lg:col-span-1">
            <Search className="w-4 h-4 text-slate-400 absolute left-3 top-1/2 -translate-y-1/2" />
            <input
              type="text"
              value={searchQuery}
              onChange={(e) => setSearchQuery(e.target.value)}
              placeholder="ค้นหาเลขที่ใบลา, ชื่อ, ตำแหน่ง..."
              className="w-full pl-9 pr-3 py-2 text-xs rounded-xl border border-slate-200 focus:outline-none focus:border-indigo-700"
            />
          </div>

          <select
            value={statusFilter}
            onChange={(e) => setStatusFilter(e.target.value)}
            className="px-3 py-2 text-xs rounded-xl border border-slate-200 bg-white"
          >
            <option value="ALL">ทุกสถานะใบลา</option>
            <option value="รอตรวจสอบ">รอตรวจสอบ</option>
            <option value="รออนุมัติ">รออนุมัติ</option>
            <option value="อนุมัติแล้ว">อนุมัติแล้ว</option>
            <option value="ส่งกลับแก้ไข">ส่งกลับแก้ไข</option>
            <option value="ไม่อนุมัติ">ไม่อนุมัติ</option>
            <option value="ร่าง">ฉบับร่าง</option>
            <option value="ยกเลิก">ยกเลิกแล้ว</option>
          </select>

          <select
            value={typeFilter}
            onChange={(e) => setTypeFilter(e.target.value)}
            className="px-3 py-2 text-xs rounded-xl border border-slate-200 bg-white"
          >
            <option value="ALL">ทุกประเภทการลา</option>
            {leaveTypes.map((lt) => (
              <option key={lt.typeId} value={lt.name}>
                {lt.name}
              </option>
            ))}
          </select>

          <select
            value={monthFilter}
            onChange={(e) => setMonthFilter(e.target.value)}
            className="px-3 py-2 text-xs rounded-xl border border-slate-200 bg-white"
          >
            <option value="ALL">ทุกเดือน</option>
            {Array.from({ length: 12 }).map((_, idx) => (
              <option key={idx} value={String(idx)}>
                {getThaiMonthName(idx)}
              </option>
            ))}
          </select>

          <select
            value={yearFilter}
            onChange={(e) => setYearFilter(e.target.value)}
            className="px-3 py-2 text-xs rounded-xl border border-slate-200 bg-white"
          >
            <option value="ALL">ทุกปี พ.ศ.</option>
            <option value="2569">พ.ศ. 2569</option>
            <option value="2568">พ.ศ. 2568</option>
            <option value="2570">พ.ศ. 2570</option>
          </select>
        </div>
      </div>

      {/* Leave Cards List */}
      {filteredLeaves.length === 0 ? (
        <div className="bg-white rounded-3xl p-10 text-center border border-slate-200 space-y-2">
          <FileText className="w-10 h-10 text-slate-300 mx-auto" />
          <div className="text-sm font-semibold text-slate-700">ไม่พบรายการใบลาตามเงื่อนไขที่ค้นหา</div>
          <p className="text-xs text-slate-400">คุณสามารถกดปุ่ม &ldquo;สร้างใบลา&rdquo; เพื่อยื่นใบลาออนไลน์ใหม่ได้ทันที</p>
        </div>
      ) : (
        <div className="space-y-3">
          {filteredLeaves.map((leave) => {
            const isOwner = leave.userId === user.userId;
            const canEdit =
              (isOwner && (leave.status === 'ร่าง' || leave.status === 'ส่งกลับแก้ไข')) ||
              user.role === 'Admin';
            const canCancel =
              (isOwner || user.role === 'Admin') &&
              leave.status !== 'ยกเลิก' &&
              leave.status !== 'ไม่อนุมัติ';

            return (
              <div
                key={leave.leaveId}
                className="bg-white rounded-2xl p-4 border border-slate-200 shadow-xs hover:border-indigo-200 transition space-y-3"
              >
                <div className="flex items-start justify-between gap-2 flex-wrap">
                  <div className="space-y-1">
                    <div className="flex items-center gap-2 flex-wrap">
                      <span className="font-mono text-xs font-bold px-2.5 py-0.5 rounded-lg bg-indigo-50 text-indigo-950 border border-indigo-200">
                        {leave.leaveNumber}
                      </span>
                      <span className="font-bold text-slate-900 text-sm">
                        {leave.leaveTypeName} ({leave.totalDays} วัน)
                      </span>
                      <span
                        className={`text-[11px] font-semibold px-2.5 py-0.5 rounded-lg border ${getStatusBadgeStyle(
                          leave.status
                        )}`}
                      >
                        {leave.status}
                      </span>
                    </div>

                    <div className="text-xs text-slate-700 font-medium">
                      ผู้ยื่นลา: <span className="font-bold text-slate-900">{leave.fullName}</span> • ตำแหน่ง:{' '}
                      {leave.position || '-'} ({leave.role})
                    </div>

                    <div className="text-xs text-slate-600 flex items-center gap-1.5 flex-wrap">
                      <Calendar className="w-3.5 h-3.5 text-indigo-700" />
                      <span>
                        วันที่ลา: <strong>{formatThaiDate(leave.startDate)}</strong> ถึง{' '}
                        <strong>{formatThaiDate(leave.endDate)}</strong> ({leave.durationType})
                      </span>
                    </div>

                    <div className="text-xs text-slate-600">
                      เหตุผล: <span className="text-slate-800">{leave.reason}</span>
                    </div>

                    {leave.returnReason && (
                      <div className="text-xs text-orange-800 bg-orange-50 px-3 py-1.5 rounded-xl border border-orange-200">
                        <strong>ส่งกลับแก้ไข:</strong> {leave.returnReason}
                      </div>
                    )}
                    {leave.rejectReason && (
                      <div className="text-xs text-rose-800 bg-rose-50 px-3 py-1.5 rounded-xl border border-rose-200">
                        <strong>เหตุผลที่ไม่อนุมัติ:</strong> {leave.rejectReason}
                      </div>
                    )}

                    {/* Google Drive File ID & URL Record Box (Synced with Google Sheets) */}
                    {leave.pdfFileId ? (
                      <div className="mt-2 p-2.5 rounded-xl bg-emerald-50/70 border border-emerald-200 text-[11px] text-emerald-950 flex flex-wrap items-center justify-between gap-2">
                        <div className="space-y-0.5 min-w-0">
                          <div className="font-bold text-emerald-900 flex items-center gap-1.5 flex-wrap">
                            <CheckCircle2 className="w-3.5 h-3.5 text-emerald-600 shrink-0" />
                            <span>บันทึกใน Google Drive &amp; Google Sheets แล้ว</span>
                            <span className="font-mono text-[10px] px-1.5 py-0.5 rounded bg-white border border-emerald-200 text-emerald-900">
                              File ID: {leave.pdfFileId}
                            </span>
                          </div>
                          <div className="text-[10px] text-emerald-800 font-mono truncate max-w-xl">
                            URL:{' '}
                            {leave.pdfWebViewLink ||
                              `https://drive.google.com/file/d/${leave.pdfFileId}/view`}
                          </div>
                        </div>
                        <div className="flex items-center gap-1.5 shrink-0">
                          <a
                            href={
                              leave.pdfWebViewLink ||
                              `https://drive.google.com/file/d/${leave.pdfFileId}/view`
                            }
                            target="_blank"
                            rel="noopener noreferrer"
                            className="inline-flex items-center gap-1 px-2.5 py-1 rounded-lg bg-emerald-700 hover:bg-emerald-800 text-white text-[11px] font-semibold"
                          >
                            <ExternalLink className="w-3 h-3" />
                            เปิดใน Drive
                          </a>
                          {leave.pdfFileUrl && (
                            <a
                              href={leave.pdfFileUrl}
                              target="_blank"
                              rel="noopener noreferrer"
                              className="inline-flex items-center gap-1 px-2 py-1 rounded-lg bg-white hover:bg-emerald-100 text-emerald-900 border border-emerald-300 text-[11px] font-semibold"
                            >
                              <Download className="w-3 h-3" />
                              ดาวน์โหลด
                            </a>
                          )}
                        </div>
                      </div>
                    ) : (
                      <div className="mt-2 p-2 rounded-xl bg-amber-50/70 border border-amber-200 text-[11px] text-amber-900 flex flex-wrap items-center justify-between gap-2">
                        <span>
                          ยังไม่ได้อัปโหลด PDF ขึ้นโฟลเดอร์ Google Drive (คลิกเพื่อสร้างโฟลเดอร์และบันทึก File ID/URL อัตโนมัติ)
                        </span>
                        <button
                          type="button"
                          onClick={() => handleQuickGenerateAndUploadDrive(leave)}
                          disabled={uploadingLeaveId === leave.leaveId}
                          className="inline-flex items-center gap-1 px-2.5 py-1 rounded-lg bg-amber-500 hover:bg-amber-600 text-slate-950 font-bold text-[11px] cursor-pointer disabled:opacity-60"
                        >
                          {uploadingLeaveId === leave.leaveId ? (
                            <Loader2 className="w-3 h-3 animate-spin" />
                          ) : (
                            <ExternalLink className="w-3 h-3" />
                          )}
                          {uploadingLeaveId === leave.leaveId
                            ? 'กำลังอัปโหลด...'
                            : 'สร้าง PDF & บันทึกลง Google Drive'}
                        </button>
                      </div>
                    )}
                  </div>

                  <div className="text-right text-[11px] text-slate-400 space-y-0.5">
                    <div>ยื่นเมื่อ: {formatThaiDate(leave.writtenDate)}</div>
                    {leave.inspectedAt && <div>ผู้ตรวจ: {leave.inspectorName}</div>}
                    {leave.approvedAt && (
                      <div className="text-emerald-700 font-medium">
                        ผู้อนุมัติ: {leave.approverName} ({formatThaiDate(leave.approvedAt)})
                      </div>
                    )}
                  </div>
                </div>

                {/* Action Bar */}
                <div className="pt-3 border-t border-slate-100 flex flex-wrap items-center justify-between gap-2">
                  <div className="flex flex-wrap items-center gap-1.5">
                    <button
                      type="button"
                      onClick={() => setPreviewLeave(leave)}
                      className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-xl bg-indigo-50 hover:bg-indigo-100 text-indigo-900 text-xs font-semibold transition cursor-pointer"
                    >
                      <Eye className="w-3.5 h-3.5" />
                      เปิดเอกสารราชการ / PDF
                    </button>

                    {leave.pdfWebViewLink && (
                      <a
                        href={leave.pdfWebViewLink}
                        target="_blank"
                        rel="noopener noreferrer"
                        className="inline-flex items-center gap-1 px-2.5 py-1.5 rounded-xl bg-slate-100 hover:bg-slate-200 text-slate-700 text-xs font-medium transition"
                      >
                        <ExternalLink className="w-3.5 h-3.5" />
                        Google Drive
                      </a>
                    )}

                    {canEdit && (
                      <button
                        type="button"
                        onClick={() => onEditLeave(leave)}
                        className="inline-flex items-center gap-1 px-2.5 py-1.5 rounded-xl bg-amber-50 hover:bg-amber-100 text-amber-900 border border-amber-200 text-xs font-semibold transition cursor-pointer"
                      >
                        <Edit3 className="w-3.5 h-3.5" />
                        แก้ไขใบลา
                      </button>
                    )}

                    {canCancel && (
                      <button
                        type="button"
                        onClick={() => {
                          if (window.confirm(`ยืนยันการยกเลิกใบลาเลขที่ ${leave.leaveNumber}?`)) {
                            onCancelLeave(leave.leaveId);
                          }
                        }}
                        className="inline-flex items-center gap-1 px-2.5 py-1.5 rounded-xl text-rose-600 hover:bg-rose-50 text-xs font-medium transition cursor-pointer"
                      >
                        <Ban className="w-3.5 h-3.5" />
                        ยกเลิก
                      </button>
                    )}
                  </div>

                  {/* Inspector / Admin Review Controls (#19) */}
                  {canReviewAllLeaves &&
                    leave.status !== 'ยกเลิก' &&
                    leave.status !== 'ร่าง' && (
                      <div className="flex flex-wrap items-center gap-1.5">
                        {(leave.status === 'รอตรวจสอบ' || leave.status === 'ส่งใบลาแล้ว') && (
                          <button
                            type="button"
                            onClick={() => openWorkflowModal(leave, 'ตรวจสอบ')}
                            className="inline-flex items-center gap-1 px-3 py-1.5 rounded-xl bg-blue-600 hover:bg-blue-700 text-white text-xs font-semibold shadow-xs transition cursor-pointer"
                          >
                            <CheckCheck className="w-3.5 h-3.5" />
                            ลงชื่อตรวจสอบ
                          </button>
                        )}

                        {leave.status !== 'อนุมัติแล้ว' && (
                          <button
                            type="button"
                            onClick={() => openWorkflowModal(leave, 'อนุมัติ')}
                            className="inline-flex items-center gap-1 px-3 py-1.5 rounded-xl bg-emerald-600 hover:bg-emerald-700 text-white text-xs font-semibold shadow-xs transition cursor-pointer"
                          >
                            <CheckCircle2 className="w-3.5 h-3.5" />
                            อนุมัติใบลา
                          </button>
                        )}

                        {leave.status !== 'อนุมัติแล้ว' && (
                          <button
                            type="button"
                            onClick={() => openWorkflowModal(leave, 'ส่งกลับแก้ไข')}
                            className="inline-flex items-center gap-1 px-2.5 py-1.5 rounded-xl bg-amber-100 hover:bg-amber-200 text-amber-900 text-xs font-semibold transition cursor-pointer"
                          >
                            <RotateCcw className="w-3.5 h-3.5" />
                            ส่งกลับแก้ไข
                          </button>
                        )}

                        {leave.status !== 'ไม่อนุมัติ' && (
                          <button
                            type="button"
                            onClick={() => openWorkflowModal(leave, 'ไม่อนุมัติ')}
                            className="inline-flex items-center gap-1 px-2.5 py-1.5 rounded-xl bg-rose-600 hover:bg-rose-700 text-white text-xs font-semibold transition cursor-pointer"
                          >
                            <XCircle className="w-3.5 h-3.5" />
                            ไม่อนุมัติ
                          </button>
                        )}
                      </div>
                    )}
                </div>
              </div>
            );
          })}
        </div>
      )}

      {/* Inspector / Director Workflow & Signature Modal (#18, #19) */}
      {workflowTarget && (
        <div className="fixed inset-0 z-50 bg-slate-900/60 backdrop-blur-xs flex items-center justify-center p-4 overflow-y-auto">
          <div className="bg-white rounded-3xl max-w-lg w-full p-5 shadow-xl space-y-4 my-8">
            <div className="border-b border-slate-100 pb-3">
              <h3 className="text-base font-bold text-slate-900">
                {workflowTarget.actionType === 'ตรวจสอบ' && 'ลงชื่อผู้ตรวจสอบสถิติการลา'}
                {workflowTarget.actionType === 'อนุมัติ' && 'อนุมัติใบลาราชการและประทับลายมือชื่อ'}
                {workflowTarget.actionType === 'ไม่อนุมัติ' && 'ระบุเหตุผลที่ไม่อนุมัติใบลา'}
                {workflowTarget.actionType === 'ส่งกลับแก้ไข' && 'ส่งกลับใบลาให้ผู้ยื่นแก้ไข'}
              </h3>
              <p className="text-xs text-slate-500">
                เลขที่ใบลา: {workflowTarget.leave.leaveNumber} • ผู้ลา: {workflowTarget.leave.fullName} (
                {workflowTarget.leave.leaveTypeName} {workflowTarget.leave.totalDays} วัน)
              </p>
            </div>

            {workflowError && (
              <div className="p-3 rounded-xl bg-rose-50 border border-rose-200 text-rose-700 text-xs font-medium">
                {workflowError}
              </div>
            )}

            <form onSubmit={handleConfirmWorkflow} className="space-y-3">
              {workflowTarget.actionType === 'ตรวจสอบ' && inspectors.length > 0 && (
                <div>
                  <label className="block text-xs font-semibold text-slate-700 mb-1">
                    เลือกผู้ตรวจสอบที่ตั้งค่าไว้
                  </label>
                  <select
                    onChange={(e) => {
                      const found = inspectors.find((i) => i.inspectorId === e.target.value);
                      if (found) {
                        setActorName(found.fullName);
                        setActorPosition(found.position);
                        if (found.signatureDataUrl) setSignatureDataUrl(found.signatureDataUrl);
                      }
                    }}
                    className="w-full px-3 py-2 rounded-xl border border-slate-200 text-sm bg-slate-50"
                  >
                    {inspectors.map((i) => (
                      <option key={i.inspectorId} value={i.inspectorId}>
                        {i.fullName} ({i.position})
                      </option>
                    ))}
                  </select>
                </div>
              )}

              <div className="grid grid-cols-1 sm:grid-cols-2 gap-2.5">
                <div>
                  <label className="block text-xs font-semibold text-slate-700 mb-1">
                    ชื่อผู้ลงนาม *
                  </label>
                  <input
                    type="text"
                    required
                    value={actorName}
                    onChange={(e) => setActorName(e.target.value)}
                    className="w-full px-3 py-2 rounded-xl border border-slate-200 text-sm"
                  />
                </div>
                <div>
                  <label className="block text-xs font-semibold text-slate-700 mb-1">
                    ตำแหน่ง *
                  </label>
                  <input
                    type="text"
                    required
                    value={actorPosition}
                    onChange={(e) => setActorPosition(e.target.value)}
                    className="w-full px-3 py-2 rounded-xl border border-slate-200 text-sm"
                  />
                </div>
              </div>

              <div>
                <label className="block text-xs font-semibold text-slate-700 mb-1">
                  {workflowTarget.actionType === 'ไม่อนุมัติ'
                    ? 'เหตุผลที่ไม่อนุมัติ *'
                    : workflowTarget.actionType === 'ส่งกลับแก้ไข'
                    ? 'ข้อความแจ้งให้ผู้ยื่นแก้ไข *'
                    : 'ความเห็นประกอบ'}
                </label>
                <textarea
                  rows={2}
                  required={
                    workflowTarget.actionType === 'ไม่อนุมัติ' ||
                    workflowTarget.actionType === 'ส่งกลับแก้ไข'
                  }
                  value={workflowComment}
                  onChange={(e) => setWorkflowComment(e.target.value)}
                  placeholder="ระบุความเห็นหรือเหตุผล..."
                  className="w-full px-3 py-2 rounded-xl border border-slate-200 text-sm"
                />
              </div>

              {(workflowTarget.actionType === 'ตรวจสอบ' ||
                workflowTarget.actionType === 'อนุมัติ') && (
                <SignaturePad
                  label={`ลายมือชื่อ${
                    workflowTarget.actionType === 'ตรวจสอบ' ? 'ผู้ตรวจสอบ' : 'ผู้อนุมัติ'
                  } (จะแสดงในเอกสาร PDF ทันที)`}
                  value={signatureDataUrl}
                  onChange={setSignatureDataUrl}
                />
              )}

              <div className="flex justify-end gap-2 pt-3 border-t border-slate-100">
                <button
                  type="button"
                  onClick={() => setWorkflowTarget(null)}
                  className="px-4 py-2 rounded-xl bg-slate-100 text-slate-700 text-xs font-semibold cursor-pointer"
                >
                  ยกเลิก
                </button>
                <button
                  type="submit"
                  disabled={isProcessingWorkflow}
                  className="inline-flex items-center gap-1.5 px-5 py-2 rounded-xl bg-indigo-900 hover:bg-indigo-800 text-white text-xs font-semibold cursor-pointer disabled:opacity-60"
                >
                  {isProcessingWorkflow && <Loader2 className="w-4 h-4 animate-spin" />}
                  ยืนยัน{workflowTarget.actionType}
                </button>
              </div>
            </form>
          </div>
        </div>
      )}
    </div>
  );
};
