import React, { useEffect, useMemo, useState } from 'react';
import {
  FilePlus2,
  Calendar,
  Clock,
  CheckCircle2,
  XCircle,
  RotateCcw,
  FileText,
  Download,
  Search,
  AlertTriangle,
  Send,
  Save,
  Loader2,
  Eye,
  Edit3,
  Ban,
  ExternalLink,
  CheckCheck,
} from 'lucide-react';
import {
  InspectorRecord,
  LeaveDurationType,
  LeaveRequest,
  LeaveType,
  SystemSettings,
  User,
} from '../types.ts';
import {
  calculateLeaveDays,
  formatThaiDate,
  getThaiMonthName,
  getTodayISO,
  parseISODateParts,
} from '../utils/thaiDate.ts';
import { generateOfficialLeavePdf } from '../utils/pdfGenerator.ts';
import { OfficialLeaveDocument } from './OfficialLeaveDocument.tsx';
import { SignaturePad } from './SignaturePad.tsx';

const LOCAL_DRAFT_KEY = 'namphong_leave_form_draft_v1';

interface CreateOrEditLeaveViewProps {
  user: User;
  settings: SystemSettings;
  leaveTypes: LeaveType[];
  existingLeaves?: LeaveRequest[];
  inspectors?: InspectorRecord[];
  editingLeave?: LeaveRequest | null;
  onSubmitLeave: (payload: any, existingLeaveId?: string) => Promise<LeaveRequest>;
  onUploadPdfToDrive: (
    leaveId: string,
    pdfBase64: string,
    fileName: string
  ) => Promise<LeaveRequest | void>;
  onCancelEdit?: () => void;
  onFinished: (createdLeave: LeaveRequest) => void;
}

export const CreateOrEditLeaveView: React.FC<CreateOrEditLeaveViewProps> = ({
  user,
  settings,
  leaveTypes,
  existingLeaves = [],
  inspectors = [],
  editingLeave,
  onSubmitLeave,
  onUploadPdfToDrive,
  onCancelEdit,
  onFinished,
}) => {
  const activeLeaveTypes = useMemo(
    () => leaveTypes.filter((lt) => lt.isActive),
    [leaveTypes]
  );

  const defaultType = activeLeaveTypes[0] || leaveTypes[0];

  const [viewMode, setViewMode] = useState<'split' | 'form' | 'a4_preview'>('split');
  const [writtenDate, setWrittenDate] = useState(editingLeave?.writtenDate || getTodayISO());
  const [leaveTypeId, setLeaveTypeId] = useState(
    editingLeave?.leaveTypeId || defaultType?.typeId || 'LT-01'
  );
  const [subject, setSubject] = useState(
    editingLeave?.subject || `ขออนุญาต${defaultType?.name || 'ลาป่วย'}`
  );
  const [addressedTo, setAddressedTo] = useState(
    editingLeave?.addressedTo || settings.addressedToDefault || 'ผู้อำนวยการสกร.ระดับอำเภอน้ำพอง'
  );
  const [requesterPosition, setRequesterPosition] = useState(
    editingLeave?.position || user.position || ''
  );
  const [requesterDepartment, setRequesterDepartment] = useState(
    editingLeave?.department || user.department || settings.organizationName || 'สกร.ระดับอำเภอน้ำพอง จ.ขอนแก่น'
  );
  const [durationType, setDurationType] = useState<LeaveDurationType>(
    editingLeave?.durationType || 'เต็มวัน'
  );
  const [startDate, setStartDate] = useState(editingLeave?.startDate || getTodayISO());
  const [endDate, setEndDate] = useState(editingLeave?.endDate || getTodayISO());
  const [excludeWeekends, setExcludeWeekends] = useState(false);
  const [reason, setReason] = useState(editingLeave?.reason || '');
  const [contactAddress, setContactAddress] = useState(
    editingLeave?.contactAddress || settings.address || 'อำเภอน้ำพอง จังหวัดขอนแก่น'
  );
  const [contactPhone, setContactPhone] = useState(editingLeave?.contactPhone || user.phone || '');
  const [substituteWork, setSubstituteWork] = useState(editingLeave?.substituteWork || '');
  const [substitutePerson, setSubstitutePerson] = useState(editingLeave?.substitutePerson || '');
  const [note, setNote] = useState(editingLeave?.note || '');
  const [requesterSignatureUrl, setRequesterSignatureUrl] = useState(
    editingLeave?.requesterSignatureUrl ||
      (editingLeave?.halfDayPeriod?.startsWith('data:image/') ? editingLeave.halfDayPeriod : '')
  );

  const [isSubmitting, setIsSubmitting] = useState(false);
  const [isDownloadingPreviewPdf, setIsDownloadingPreviewPdf] = useState(false);
  const [stepStatus, setStepStatus] = useState('');
  const [errorMsg, setErrorMsg] = useState('');
  const [hasRestoredDraft, setHasRestoredDraft] = useState(false);

  // Automatic Sequential Leave Number Calculation (e.g. LV-2569-0001)
  const autoGeneratedLeaveNumber = useMemo(() => {
    if (editingLeave?.leaveNumber) return editingLeave.leaveNumber;
    const prefix = settings.leaveNumberPrefix || 'LV';
    const fiscalYear = settings.fiscalYear || '2569';
    const pattern = `${prefix}-${fiscalYear}-`;
    let maxSeq = 0;
    existingLeaves.forEach((l) => {
      if (l.leaveNumber && l.leaveNumber.startsWith(pattern)) {
        const numPart = parseInt(l.leaveNumber.replace(pattern, ''), 10);
        if (!isNaN(numPart) && numPart > maxSeq) maxSeq = numPart;
      }
    });
    const nextSeq = String(maxSeq + 1).padStart(4, '0');
    return `${pattern}${nextSeq}`;
  }, [editingLeave?.leaveNumber, existingLeaves, settings.leaveNumberPrefix, settings.fiscalYear]);

  // Restore local draft if creating new leave (#30)
  useEffect(() => {
    if (editingLeave) return;
    try {
      const saved = localStorage.getItem(LOCAL_DRAFT_KEY);
      if (saved) {
        const parsed = JSON.parse(saved);
        if (parsed && parsed.reason) {
          setLeaveTypeId(parsed.leaveTypeId || defaultType?.typeId || 'LT-01');
          setSubject(parsed.subject || `ขออนุญาต${defaultType?.name || 'ลาป่วย'}`);
          setDurationType(parsed.durationType || 'เต็มวัน');
          setStartDate(parsed.startDate || getTodayISO());
          setEndDate(parsed.endDate || getTodayISO());
          setReason(parsed.reason || '');
          setContactAddress(parsed.contactAddress || settings.address);
          setContactPhone(parsed.contactPhone || user.phone);
          setSubstituteWork(parsed.substituteWork || '');
          setSubstitutePerson(parsed.substitutePerson || '');
          setNote(parsed.note || '');
          if (parsed.requesterSignatureUrl) setRequesterSignatureUrl(parsed.requesterSignatureUrl);
          setHasRestoredDraft(true);
        }
      }
    } catch {
      // ignore
    }
  }, [editingLeave]);

  // Save draft to localStorage automatically so user never loses form data (#22, #30)
  useEffect(() => {
    if (editingLeave) return;
    try {
      localStorage.setItem(
        LOCAL_DRAFT_KEY,
        JSON.stringify({
          leaveTypeId,
          subject,
          durationType,
          startDate,
          endDate,
          reason,
          contactAddress,
          contactPhone,
          substituteWork,
          substitutePerson,
          note,
          requesterSignatureUrl,
        })
      );
    } catch {
      // ignore
    }
  }, [
    editingLeave,
    leaveTypeId,
    subject,
    durationType,
    startDate,
    endDate,
    reason,
    contactAddress,
    contactPhone,
    substituteWork,
    substitutePerson,
    note,
    requesterSignatureUrl,
  ]);

  const selectedLeaveType = useMemo(
    () => leaveTypes.find((lt) => lt.typeId === leaveTypeId),
    [leaveTypes, leaveTypeId]
  );

  const handleLeaveTypeChange = (newTypeId: string) => {
    setLeaveTypeId(newTypeId);
    const found = leaveTypes.find((lt) => lt.typeId === newTypeId);
    if (found) {
      setSubject(`ขออนุญาต${found.name}`);
    }
  };

  // Auto-calculate total days (#12)
  const totalDays = useMemo(() => {
    const effEnd = durationType.includes('ครึ่งวัน') ? startDate : endDate;
    return calculateLeaveDays(startDate, effEnd, durationType, excludeWeekends);
  }, [startDate, endDate, durationType, excludeWeekends]);

  // Calculate user's previous leave statistics of same category in this fiscal year
  const userLeaveStats = useMemo(() => {
    const userApprovedLeaves = existingLeaves
      .filter(
        (l) =>
          l.userId === user.userId &&
          l.status === 'อนุมัติแล้ว' &&
          l.leaveId !== editingLeave?.leaveId
      )
      .sort((a, b) => (b.startDate || '').localeCompare(a.startDate || ''));

    const lastSameType = userApprovedLeaves.find((l) => l.leaveTypeId === leaveTypeId);
    const accumulated = userApprovedLeaves
      .filter((l) => l.leaveTypeId === leaveTypeId)
      .reduce((sum, l) => sum + (Number(l.totalDays) || 0), 0);

    return {
      lastLeaveType: lastSameType?.leaveTypeName || selectedLeaveType?.name || 'ลาป่วย',
      lastLeaveStartDate: lastSameType?.startDate || '',
      lastLeaveEndDate: lastSameType?.endDate || '',
      lastLeaveTotalDays: lastSameType?.totalDays || 0,
      accumulatedLeaveDays: accumulated,
    };
  }, [existingLeaves, user.userId, editingLeave?.leaveId, leaveTypeId, selectedLeaveType?.name]);

  const defaultInspector = useMemo(
    () =>
      inspectors.find((i) => i.isDefault && i.isActive) ||
      inspectors.find((i) => i.isActive),
    [inspectors]
  );

  // Build Live Preview Leave Request Object for Official Thai Government A4 Form & Real PDF
  const livePreviewLeave: LeaveRequest = useMemo(() => {
    const effectiveEndDate = durationType.includes('ครึ่งวัน') ? startDate : endDate;
    return {
      leaveId: editingLeave?.leaveId || 'PREVIEW-LIVE',
      leaveNumber: autoGeneratedLeaveNumber,
      userId: user.userId,
      username: user.username,
      fullName: user.fullName,
      position: requesterPosition || user.position || '-',
      department: requesterDepartment || user.department || settings.organizationName,
      role: user.role,
      writtenDate,
      subject: subject || `ขออนุญาต${selectedLeaveType?.name || 'ลาป่วย'}`,
      addressedTo: addressedTo || settings.addressedToDefault,
      leaveTypeId,
      leaveTypeName: selectedLeaveType?.name || 'ลาป่วย',
      startDate,
      endDate: effectiveEndDate,
      durationType,
      halfDayPeriod: requesterSignatureUrl || durationType,
      requesterSignatureUrl,
      totalDays: totalDays > 0 ? totalDays : 0,
      reason: reason || '-',
      contactAddress: contactAddress || settings.address,
      contactPhone: contactPhone || user.phone || '-',
      substituteWork: substituteWork || '-',
      substitutePerson: substitutePerson || '-',
      note: note || '',
      status: editingLeave?.status || 'รอตรวจสอบ',
      lastLeaveType: editingLeave?.lastLeaveType || userLeaveStats.lastLeaveType,
      lastLeaveStartDate: editingLeave?.lastLeaveStartDate ?? userLeaveStats.lastLeaveStartDate,
      lastLeaveEndDate: editingLeave?.lastLeaveEndDate ?? userLeaveStats.lastLeaveEndDate,
      lastLeaveTotalDays: editingLeave?.lastLeaveTotalDays ?? userLeaveStats.lastLeaveTotalDays,
      accumulatedLeaveDays:
        editingLeave?.accumulatedLeaveDays ?? userLeaveStats.accumulatedLeaveDays,
      inspectorName:
        editingLeave?.inspectorName ||
        defaultInspector?.fullName ||
        settings.defaultInspectorName,
      inspectorPosition:
        editingLeave?.inspectorPosition ||
        defaultInspector?.position ||
        settings.defaultInspectorPosition,
      inspectorComment: editingLeave?.inspectorComment || '',
      inspectorSignatureUrl: editingLeave?.inspectorSignatureUrl || '',
      inspectedAt: editingLeave?.inspectedAt || '',
      approverName: editingLeave?.approverName || settings.directorName,
      approverPosition: editingLeave?.approverPosition || settings.directorPosition,
      approverComment: editingLeave?.approverComment || '',
      approverSignatureUrl: editingLeave?.approverSignatureUrl || '',
      approvedAt: editingLeave?.approvedAt || '',
      returnReason: editingLeave?.returnReason || '',
      rejectReason: editingLeave?.rejectReason || '',
      pdfFileId: editingLeave?.pdfFileId || '',
      pdfFileUrl: editingLeave?.pdfFileUrl || '',
      pdfWebViewLink: editingLeave?.pdfWebViewLink || '',
      createdAt: editingLeave?.createdAt || new Date().toISOString(),
      updatedAt: new Date().toISOString(),
    };
  }, [
    editingLeave,
    autoGeneratedLeaveNumber,
    user,
    requesterPosition,
    requesterDepartment,
    settings,
    writtenDate,
    subject,
    selectedLeaveType,
    addressedTo,
    leaveTypeId,
    startDate,
    endDate,
    durationType,
    requesterSignatureUrl,
    totalDays,
    reason,
    contactAddress,
    contactPhone,
    substituteWork,
    substitutePerson,
    note,
    userLeaveStats,
    defaultInspector,
  ]);

  const handleDirectDownloadPdf = async () => {
    try {
      setIsDownloadingPreviewPdf(true);
      const { pdfBlob, fileName } = await generateOfficialLeavePdf(livePreviewLeave, settings);
      const url = URL.createObjectURL(pdfBlob);
      const a = document.createElement('a');
      a.href = url;
      a.download = fileName;
      document.body.appendChild(a);
      a.click();
      document.body.removeChild(a);
      setTimeout(() => URL.revokeObjectURL(url), 10000);
    } finally {
      setIsDownloadingPreviewPdf(false);
    }
  };

  const handleSave = async (submitNow: boolean) => {
    setErrorMsg('');

    if (!leaveTypeId) {
      setErrorMsg('กรุณาเลือกประเภทการลา');
      return;
    }
    const effectiveEndDate = durationType.includes('ครึ่งวัน') ? startDate : endDate;
    if (!startDate || !effectiveEndDate) {
      setErrorMsg('กรุณาระบุวันที่เริ่มลาและถึงวันที่ให้ครบถ้วน');
      return;
    }
    if (effectiveEndDate < startDate) {
      setErrorMsg('วันที่สิ้นสุดการลาต้องไม่น้อยกว่าวันที่เริ่มลา');
      return;
    }
    if (totalDays <= 0) {
      setErrorMsg('จำนวนวันลาต้องมากกว่า 0 วัน');
      return;
    }
    if (!reason.trim()) {
      setErrorMsg('กรุณากรอกเหตุผลการลา');
      return;
    }
    const phoneClean = contactPhone.replace(/[\s-]/g, '');
    if (!/^[0-9]{9,10}$/.test(phoneClean)) {
      setErrorMsg('กรุณากรอกเบอร์โทรศัพท์ที่ติดต่อได้ระหว่างลา (ตัวเลข 9-10 หลัก)');
      return;
    }

    setIsSubmitting(true);
    try {
      setStepStatus('กำลังรันเลขที่ใบลาอัตโนมัติและบันทึกลงใน Google Sheets...');
      const savedLeave = await onSubmitLeave(
        {
          writtenDate,
          subject,
          addressedTo,
          position: requesterPosition || user.position,
          department: requesterDepartment || user.department || settings.organizationName,
          leaveTypeId,
          leaveTypeName: selectedLeaveType?.name || 'ลาป่วย',
          startDate,
          endDate: effectiveEndDate,
          durationType,
          requesterSignatureUrl,
          totalDays,
          reason,
          contactAddress,
          contactPhone,
          substituteWork,
          substitutePerson,
          note,
          submitNow,
        },
        editingLeave?.leaveId
      );

      // Clear local draft once saved to Google Sheets
      try {
        localStorage.removeItem(LOCAL_DRAFT_KEY);
      } catch {
        // ignore
      }

      // Generate official A4 PDF (TH-Sarabun-PSK 16pt) and upload to Google Drive (#15)
      let finalLeave = savedLeave;
      try {
        setStepStatus(
          'กำลังสร้างโฟลเดอร์ Google Drive อัตโนมัติ และบันทึก PDF พร้อม File ID/URL ลง Google Sheets...'
        );
        const { pdfBase64, fileName } = await generateOfficialLeavePdf(savedLeave, settings);
        const uploadedLeave = await onUploadPdfToDrive(savedLeave.leaveId, pdfBase64, fileName);
        if (uploadedLeave) {
          finalLeave = uploadedLeave;
        }
      } catch {
        // Non-fatal if Drive upload is retried in preview screen
      }

      onFinished(finalLeave);
    } catch (err: any) {
      setErrorMsg(
        err.message ||
          'ไม่สามารถเชื่อมต่อ Google Sheets ได้ ระบบได้เก็บข้อมูลของคุณไว้ในแบบฟอร์มแล้ว กรุณาตรวจสอบการเชื่อมต่อแล้วกดลองใหม่'
      );
    } finally {
      setIsSubmitting(false);
      setStepStatus('');
    }
  };

  return (
    <div className="space-y-4">
      {/* Top Official Banner: Automatic Leave Number + TH-Sarabun-PSK 16pt A4 Controls */}
      <div className="no-print bg-white rounded-3xl border border-slate-200 shadow-xs p-4 sm:p-5 space-y-3.5">
        <div className="flex items-start justify-between flex-wrap gap-3">
          <div className="space-y-1">
            <div className="flex items-center gap-2 flex-wrap">
              <h2 className="text-lg font-bold text-slate-900 flex items-center gap-2">
                <FilePlus2 className="w-5 h-5 text-indigo-800" />
                {editingLeave
                  ? `แก้ไขใบลาราชการ เลขที่ ${editingLeave.leaveNumber}`
                  : 'สร้างใบลาราชการไทย (A4 • TH-Sarabun-PSK 16 pt)'}
              </h2>
              <span className="px-3 py-1 rounded-xl bg-indigo-950 text-amber-300 font-mono text-xs font-bold shadow-2xs">
                เลขที่ใบลาอัตโนมัติ: {autoGeneratedLeaveNumber}
              </span>
            </div>
            <p className="text-xs text-slate-500">
              แบบฟอร์มมาตรฐานราชการไทย ขนาด A4 (210 × 297 มม.) • ฟอนต์{' '}
              <strong className="text-slate-700">TH-Sarabun-PSK 16 pt</strong> • สร้างไฟล์ PDF จริงและรันเลขทะเบียนใบลาอัตโนมัติ
            </p>
          </div>

          <div className="flex flex-wrap items-center gap-2">
            <button
              type="button"
              onClick={handleDirectDownloadPdf}
              disabled={isDownloadingPreviewPdf}
              className="inline-flex items-center gap-1.5 px-3.5 py-2 rounded-xl bg-indigo-900 hover:bg-indigo-800 text-white text-xs font-bold shadow-xs transition cursor-pointer disabled:opacity-60"
            >
              {isDownloadingPreviewPdf ? (
                <Loader2 className="w-4 h-4 animate-spin" />
              ) : (
                <Download className="w-4 h-4" />
              )}
              สร้างและดาวน์โหลด PDF จริง (.pdf)
            </button>

            {hasRestoredDraft && !editingLeave && (
              <button
                type="button"
                onClick={() => {
                  localStorage.removeItem(LOCAL_DRAFT_KEY);
                  setReason('');
                  setRequesterSignatureUrl('');
                  setHasRestoredDraft(false);
                }}
                className="px-3 py-2 rounded-xl bg-slate-100 hover:bg-slate-200 text-xs text-slate-700 font-medium cursor-pointer"
              >
                ล้างร่างที่ค้างไว้
              </button>
            )}
          </div>
        </div>

        {/* View Mode Switcher */}
        <div className="flex flex-wrap items-center justify-between gap-2 pt-2 border-t border-slate-100">
          <div className="inline-flex rounded-2xl bg-slate-100 p-1 gap-1">
            <button
              type="button"
              onClick={() => setViewMode('split')}
              className={`px-3 py-1.5 rounded-xl text-xs font-semibold transition cursor-pointer ${
                viewMode === 'split'
                  ? 'bg-white text-indigo-950 shadow-2xs'
                  : 'text-slate-600 hover:text-slate-900'
              }`}
            >
              กรอกข้อมูล + กระดาษ A4 สด
            </button>
            <button
              type="button"
              onClick={() => setViewMode('form')}
              className={`px-3 py-1.5 rounded-xl text-xs font-semibold transition cursor-pointer ${
                viewMode === 'form'
                  ? 'bg-white text-indigo-950 shadow-2xs'
                  : 'text-slate-600 hover:text-slate-900'
              }`}
            >
              เฉพาะฟอร์มกรอกข้อมูล
            </button>
            <button
              type="button"
              onClick={() => setViewMode('a4_preview')}
              className={`px-3 py-1.5 rounded-xl text-xs font-semibold transition cursor-pointer ${
                viewMode === 'a4_preview'
                  ? 'bg-white text-indigo-950 shadow-2xs'
                  : 'text-slate-600 hover:text-slate-900'
              }`}
            >
              ดูแบบฟอร์มราชการ A4 เต็มหน้า (TH-Sarabun-PSK 16 pt)
            </button>
          </div>

          <div className="text-[11px] text-slate-500">
            ปีงบประมาณ พ.ศ. <strong>{settings.fiscalYear || '2569'}</strong> • ลำดับถัดไป:{' '}
            <strong className="text-indigo-900 font-mono">{autoGeneratedLeaveNumber}</strong>
          </div>
        </div>
      </div>

      {editingLeave?.returnReason && (
        <div className="no-print p-3.5 rounded-2xl bg-amber-50 border border-amber-200 text-amber-900 text-xs space-y-1">
          <div className="font-bold flex items-center gap-1.5">
            <AlertTriangle className="w-4 h-4 text-amber-600" />
            ข้อความแจ้งให้แก้ไขจากผู้ตรวจสอบ:
          </div>
          <div>{editingLeave.returnReason}</div>
        </div>
      )}

      {errorMsg && (
        <div className="no-print p-4 rounded-2xl bg-rose-50 border border-rose-200 text-rose-800 text-xs space-y-1.5">
          <div className="font-bold flex items-center gap-1.5">
            <AlertTriangle className="w-4 h-4 text-rose-600 shrink-0" />
            ไม่สามารถบันทึกข้อมูลได้ (ข้อมูลในแบบฟอร์มไม่สูญหาย):
          </div>
          <p>{errorMsg}</p>
        </div>
      )}

      <div
        className={
          viewMode === 'split'
            ? 'grid grid-cols-1 xl:grid-cols-12 gap-5 items-start'
            : 'space-y-5'
        }
      >
        {/* LEFT / FORM PANEL */}
        {viewMode !== 'a4_preview' && (
          <div
            className={`${
              viewMode === 'split' ? 'xl:col-span-5' : ''
            } no-print bg-white rounded-3xl border border-slate-200 shadow-xs p-4 sm:p-6 space-y-5`}
          >
            {/* Automatic Leave Number & Requester Official Header */}
            <div className="bg-indigo-950 text-white rounded-2xl p-3.5 space-y-2">
              <div className="flex items-center justify-between gap-2">
                <span className="text-[11px] text-indigo-200 font-medium">
                  เลขทะเบียนใบลาอัตโนมัติ
                </span>
                <span className="px-2.5 py-0.5 rounded-lg bg-amber-400 text-slate-950 font-mono text-xs font-bold">
                  {autoGeneratedLeaveNumber}
                </span>
              </div>
              <div className="grid grid-cols-1 sm:grid-cols-2 gap-1.5 text-xs pt-1 border-t border-white/10">
                <div>
                  <span className="text-indigo-300">ข้าพเจ้า:</span>{' '}
                  <span className="font-bold">{user.fullName}</span>
                </div>
                <div>
                  <span className="text-indigo-300">ประเภทบุคลากร:</span>{' '}
                  <span className="font-semibold text-amber-200">{user.role}</span>
                </div>
              </div>
            </div>

            {/* Form Inputs */}
            <div className="grid grid-cols-1 sm:grid-cols-2 gap-3.5">
              <div>
                <label className="block text-xs font-semibold text-slate-700 mb-1">
                  วันที่เขียนใบลา ({formatThaiDate(writtenDate)}) *
                </label>
                <input
                  type="date"
                  value={writtenDate}
                  onChange={(e) => setWrittenDate(e.target.value)}
                  className="w-full px-3.5 py-2.5 rounded-xl border border-slate-200 text-sm focus:outline-none focus:border-indigo-700"
                />
              </div>

              <div>
                <label className="block text-xs font-semibold text-slate-700 mb-1">ประเภทการลา *</label>
                <select
                  value={leaveTypeId}
                  onChange={(e) => handleLeaveTypeChange(e.target.value)}
                  className="w-full px-3.5 py-2.5 rounded-xl border border-slate-200 text-sm bg-white focus:outline-none focus:border-indigo-700 font-semibold text-indigo-950"
                >
                  {activeLeaveTypes.map((lt) => (
                    <option key={lt.typeId} value={lt.typeId}>
                      {lt.name} (เพดาน {lt.maxDaysPerYear} วัน)
                    </option>
                  ))}
                </select>
                {selectedLeaveType?.conditionText && (
                  <p className="text-[11px] text-slate-500 mt-1">
                    เงื่อนไข: {selectedLeaveType.conditionText}
                  </p>
                )}
              </div>

              <div>
                <label className="block text-xs font-semibold text-slate-700 mb-1">เรื่อง *</label>
                <input
                  type="text"
                  value={subject}
                  onChange={(e) => setSubject(e.target.value)}
                  className="w-full px-3.5 py-2.5 rounded-xl border border-slate-200 text-sm"
                />
              </div>

              <div>
                <label className="block text-xs font-semibold text-slate-700 mb-1">เรียน *</label>
                <input
                  type="text"
                  value={addressedTo}
                  onChange={(e) => setAddressedTo(e.target.value)}
                  className="w-full px-3.5 py-2.5 rounded-xl border border-slate-200 text-sm"
                />
              </div>

              <div>
                <label className="block text-xs font-semibold text-slate-700 mb-1">ตำแหน่ง *</label>
                <input
                  type="text"
                  value={requesterPosition}
                  onChange={(e) => setRequesterPosition(e.target.value)}
                  className="w-full px-3.5 py-2.5 rounded-xl border border-slate-200 text-sm"
                />
              </div>

              <div>
                <label className="block text-xs font-semibold text-slate-700 mb-1">
                  สังกัด / เขียนที่ *
                </label>
                <input
                  type="text"
                  value={requesterDepartment}
                  onChange={(e) => setRequesterDepartment(e.target.value)}
                  className="w-full px-3.5 py-2.5 rounded-xl border border-slate-200 text-sm"
                />
              </div>

              {/* Duration Type Selection */}
              <div className="sm:col-span-2">
                <label className="block text-xs font-semibold text-slate-700 mb-1.5">
                  รูปแบบระยะเวลาการลา *
                </label>
                <div className="grid grid-cols-1 sm:grid-cols-3 gap-2">
                  {(
                    [
                      'เต็มวัน',
                      'ครึ่งวันเช้า (08.30 - 12.00 น.)',
                      'ครึ่งวันบ่าย (13.00 - 16.30 น.)',
                    ] as LeaveDurationType[]
                  ).map((dt) => (
                    <button
                      key={dt}
                      type="button"
                      onClick={() => {
                        setDurationType(dt);
                        if (dt.includes('ครึ่งวัน')) {
                          setEndDate(startDate);
                        }
                      }}
                      className={`py-2.5 px-3 rounded-xl border text-xs font-semibold transition cursor-pointer ${
                        durationType === dt
                          ? 'bg-indigo-900 text-white border-indigo-900 shadow-xs'
                          : 'bg-white text-slate-700 border-slate-200 hover:bg-slate-50'
                      }`}
                    >
                      {dt}
                    </button>
                  ))}
                </div>
              </div>

              <div>
                <label className="block text-xs font-semibold text-slate-700 mb-1">
                  ตั้งแต่วันที่ ({formatThaiDate(startDate)}) *
                </label>
                <input
                  type="date"
                  value={startDate}
                  onChange={(e) => {
                    setStartDate(e.target.value);
                    if (durationType.includes('ครึ่งวัน') || e.target.value > endDate) {
                      setEndDate(e.target.value);
                    }
                  }}
                  className="w-full px-3.5 py-2.5 rounded-xl border border-slate-200 text-sm"
                />
              </div>

              <div>
                <label className="block text-xs font-semibold text-slate-700 mb-1">
                  ถึงวันที่ ({formatThaiDate(durationType.includes('ครึ่งวัน') ? startDate : endDate)}) *
                </label>
                <input
                  type="date"
                  disabled={durationType.includes('ครึ่งวัน')}
                  min={startDate}
                  value={durationType.includes('ครึ่งวัน') ? startDate : endDate}
                  onChange={(e) => setEndDate(e.target.value)}
                  className="w-full px-3.5 py-2.5 rounded-xl border border-slate-200 text-sm disabled:bg-slate-100"
                />
              </div>

              {/* Auto-calculated Total Days & Fiscal Year Stats Summary */}
              <div className="sm:col-span-2 bg-indigo-50/80 border border-indigo-200 rounded-2xl p-3.5 space-y-2">
                <div className="flex flex-wrap items-center justify-between gap-2">
                  <div className="flex items-center gap-2">
                    <Clock className="w-4 h-4 text-indigo-800" />
                    <div className="text-xs text-indigo-950 font-semibold">
                      ลาครั้งนี้:{' '}
                      <span className="text-sm font-bold text-indigo-900">
                        {totalDays > 0 ? totalDays : 0} วัน
                      </span>{' '}
                      • ลามาแล้วปีงบฯ นี้:{' '}
                      <span className="font-bold">{userLeaveStats.accumulatedLeaveDays} วัน</span> • รวมเป็น:{' '}
                      <span className="font-bold text-emerald-800">
                        {userLeaveStats.accumulatedLeaveDays + (totalDays > 0 ? totalDays : 0)} วัน
                      </span>
                    </div>
                  </div>

                  {!durationType.includes('ครึ่งวัน') && (
                    <label className="flex items-center gap-1.5 text-xs font-medium text-indigo-900 cursor-pointer">
                      <input
                        type="checkbox"
                        checked={excludeWeekends}
                        onChange={(e) => setExcludeWeekends(e.target.checked)}
                        className="rounded text-indigo-900"
                      />
                      ไม่นับเสาร์-อาทิตย์
                    </label>
                  )}
                </div>
              </div>

              <div className="sm:col-span-2">
                <label className="block text-xs font-semibold text-slate-700 mb-1">
                  เหตุผลการลา (เนื่องจาก) *
                </label>
                <textarea
                  rows={2}
                  required
                  value={reason}
                  onChange={(e) => setReason(e.target.value)}
                  placeholder="ระบุเหตุผลการลาอย่างชัดเจนตามระเบียบราชการ..."
                  className="w-full px-3.5 py-2.5 rounded-xl border border-slate-200 text-sm"
                />
              </div>

              <div>
                <label className="block text-xs font-semibold text-slate-700 mb-1">
                  ในระหว่างลาติดต่อข้าพเจ้าได้ที่ *
                </label>
                <input
                  type="text"
                  value={contactAddress}
                  onChange={(e) => setContactAddress(e.target.value)}
                  className="w-full px-3.5 py-2.5 rounded-xl border border-slate-200 text-sm"
                />
              </div>

              <div>
                <label className="block text-xs font-semibold text-slate-700 mb-1">
                  เบอร์โทรศัพท์ติดต่อระหว่างลา *
                </label>
                <input
                  type="tel"
                  value={contactPhone}
                  onChange={(e) => setContactPhone(e.target.value)}
                  placeholder="08X-XXXXXXX"
                  className="w-full px-3.5 py-2.5 rounded-xl border border-slate-200 text-sm"
                />
              </div>

              <div>
                <label className="block text-xs font-semibold text-slate-700 mb-1">
                  มอบหมายงานในหน้าที่ให้ (ชื่อผู้รับมอบ)
                </label>
                <input
                  type="text"
                  value={substitutePerson}
                  onChange={(e) => setSubstitutePerson(e.target.value)}
                  placeholder="ระบุชื่อ-นามสกุลผู้ปฏิบัติงานแทน (ถ้ามี)"
                  className="w-full px-3.5 py-2.5 rounded-xl border border-slate-200 text-sm"
                />
              </div>

              <div>
                <label className="block text-xs font-semibold text-slate-700 mb-1">
                  งานที่มอบหมายให้รับผิดชอบแทน
                </label>
                <input
                  type="text"
                  value={substituteWork}
                  onChange={(e) => setSubstituteWork(e.target.value)}
                  placeholder="เช่น งานการเรียนการสอน / งานธุรการ"
                  className="w-full px-3.5 py-2.5 rounded-xl border border-slate-200 text-sm"
                />
              </div>

              <div className="sm:col-span-2">
                <label className="block text-xs font-semibold text-slate-700 mb-1">
                  หมายเหตุเพิ่มเติม
                </label>
                <input
                  type="text"
                  value={note}
                  onChange={(e) => setNote(e.target.value)}
                  placeholder="ระบุหมายเหตุเพิ่มเติม (ถ้ามี)"
                  className="w-full px-3.5 py-2.5 rounded-xl border border-slate-200 text-sm"
                />
              </div>

              {/* Requester Digital Signature Pad */}
              <div className="sm:col-span-2 pt-1">
                <SignaturePad
                  label="ลงลายมือชื่อผู้ขอลา (แสดงบนแบบฟอร์มราชการไทย A4 และในไฟล์ PDF จริง)"
                  value={requesterSignatureUrl}
                  onChange={setRequesterSignatureUrl}
                />
              </div>
            </div>

            {/* Action Buttons */}
            <div className="pt-4 border-t border-slate-100 flex flex-wrap items-center justify-end gap-2.5">
              {onCancelEdit && (
                <button
                  type="button"
                  onClick={onCancelEdit}
                  className="px-4 py-2.5 rounded-xl bg-slate-100 hover:bg-slate-200 text-slate-700 text-xs font-semibold cursor-pointer"
                >
                  ยกเลิก
                </button>
              )}

              <button
                type="button"
                disabled={isSubmitting}
                onClick={() => handleSave(false)}
                className="inline-flex items-center gap-1.5 px-4 py-2.5 rounded-xl bg-slate-200 hover:bg-slate-300 text-slate-800 text-xs font-semibold transition cursor-pointer disabled:opacity-60"
              >
                <Save className="w-4 h-4" />
                บันทึกฉบับร่าง
              </button>

              <button
                type="button"
                disabled={isSubmitting}
                onClick={() => handleSave(true)}
                className="inline-flex items-center gap-2 px-5 py-2.5 rounded-xl bg-gradient-to-r from-indigo-900 to-purple-900 hover:from-indigo-800 hover:to-purple-800 text-white text-xs font-bold shadow-sm transition cursor-pointer disabled:opacity-60"
              >
                {isSubmitting ? (
                  <Loader2 className="w-4 h-4 animate-spin" />
                ) : (
                  <Send className="w-4 h-4" />
                )}
                {isSubmitting
                  ? stepStatus || 'กำลังส่งใบลา...'
                  : `ยืนยันส่งใบลา (${autoGeneratedLeaveNumber}) และสร้าง PDF จริง`}
              </button>
            </div>
          </div>
        )}

        {/* RIGHT / LIVE OFFICIAL THAI GOVERNMENT A4 FORM PREVIEW (TH-Sarabun-PSK 16 pt) */}
        {viewMode !== 'form' && (
          <div className={viewMode === 'split' ? 'xl:col-span-7' : ''}>
            <OfficialLeaveDocument
              leave={livePreviewLeave}
              settings={settings}
              onUploadToDrive={editingLeave ? onUploadPdfToDrive : undefined}
              compactToolbar={viewMode === 'split'}
            />
          </div>
        )}
      </div>
    </div>
  );
};

